#!/usr/bin/env python3
"""Write SHOTLIST.md, COMPONENTS.md, PROMPTS.md and RIFF.md from the beat sheet
and the ledger in checks/game/, so the paperwork cannot drift from the film.

    python3 tools/make_docs.py
"""
import json
from pathlib import Path

REEL = Path(__file__).resolve().parents[1]
sheet = json.loads((REEL / "beat_sheet.json").read_text())
ledgers = {p: json.loads((REEL / f"checks/{p}/gamedev-evidence.json").read_text()) for p in ("game",)}
beats = sheet["beats"]
title = sheet["metadata"]["title"]

NEXT = {  # one suggested experiment per evidence beat (RIFF.md)
    "B02": "Play a minute at normal speed with the sound muted and note whether you can tell the run, the slash and the hurt apart.",
    "B04": "Swap hframes and vframes in a copy (4 and 2, say) and predict which picture cell 1 shows before you run it.",
    "B06": "Count the ticks of each cell yourself in a 60 fps run and compare them with the pin's 8, 8, 7, 8, 7, 8, 7, 7.",
    "B07": "Watch at least five wraps of each form at normal speed and write down how many you watched.",
    "B09": "Read Grip's angle off each replay frame and compare it with value_track_interpolate() on that tick.",
    "B10": "Rename Arc's subname modulate:a to modulate:alpha in a copy: does track_problems() alone catch it, and why does check 1b exist?",
    "B12": "In a copy, call the old texture swap beside the player and look for the flicker the brief predicted.",
    "B14": "Set callback_mode_process to idle in a copy, rerun the state test at 30 fps, and see by how much the clip trails the hitbox.",
    "B17": "Capture the preview at 60 fps instead and check every tick 0-17 against the table, one tick a frame.",
    "B18": "Watch r1 at normal speed and say whether frames 34-35 read as a settle or as a catch, before reading Claude's comparison.",
    "B20": "Press slash again on swing ticks 17 and 18 in play and check which one starts a new swing, and why.",
    "B22": "Time a hit on swing tick 10 and on 11 in a copy, and check that sparks fire only when a live tick came before the hit.",
    "B23": "Move one key time by 1/60 s in a copy and predict which read-back line fails, and with what message.",
    "B24": "Run M4 on an imported rig instead (a .glb with a clip) and predict whether it still passes.",
    "B25": "Turn on Visible Collision Shapes in play and judge the hitbox against the blade on ticks 2-4 yourself.",
}


def dur(b):
    return b.get("actual_duration_s") or 0.0


def visual(b):
    s = b["shot"]
    if s.get("capture_plan"):
        cp = s["capture_plan"]
        segs = ", ".join(f"{x['from']}–{x['to'] - 1}" + (f" at {x['speed']:.2g}×" if x["speed"] != 1.0 else "") for x in cp["segments"])
        hold = cp.get("held_final_frames", 0)
        segs = ", ".join(f"{x['capture']} {x['from']}–{x['to'] - 1}" + (f" at {x['speed']:.2g}×" if x["speed"] != 1.0 else "") for x in cp["segments"])
        return f"capture frames {segs}" + (f" + held {hold} f" if hold else "")
    if s.get("still_plan"):
        return f"still `{s['still_plan']['image']}`"
    r = s["remotion"]
    p = r["props"]
    extra = f" `{b['excerpt']['project']}/{b['excerpt']['path']}:{b['excerpt']['start_line']}–{b['excerpt']['end_line']}`" if b.get("excerpt") else ""
    img = f" `{p['image'].rsplit('/', 1)[-1]}`" if p.get("image") else ""
    return f"{r['pattern']}" + (f" ({p.get('mode')})" if p.get("mode") else "") + extra + img


t = 0.0
rows = []
for b in beats:
    rows.append(f"| {b['beat_id']} | {t:6.1f} | {dur(b):5.1f} | {b['act']} | {visual(b)} |")
    t += dur(b)
(REEL / "SHOTLIST.md").write_text(
    f"# SHOTLIST — {title}\n\n{len(beats)} beats, {t:.1f} s ({int(t // 60)}:{t % 60:04.1f}), 3840×2160, 30 fps. "
    "Generated by `tools/make_docs.py` from `beat_sheet.json`.\n\n"
    "Every Godot code beat is followed by its visible result (`code-then-result-v1`), always real engine output: a hashed Movie Maker take of the "
    "running game (`play-01` to `play-03`, CAPTURE.md) or a committed frame strip, labelled as a fixture capture. Recorded logs appear only on their own "
    "labelled cards, never as the result of a code beat.\n\n"
    "| Beat | Start s | Dur s | Act | Visual |\n| --- | ---: | ---: | --- | --- |\n" + "\n".join(rows) + "\n")

out = [f"# COMPONENTS — {title}\n",
       "One Godot project, `game/`, one ledger: `checks/game/gamedev-evidence.json` (see `tools/make_evidence.py`). "
       "`.uid` identifiers and `.godot/` are left out by the contract.\n"]
for p, ev in ledgers.items():
    out.append(f"## `{p}/` at `{ev['game']['revision'][:7]}` — {len(ev['files'])} files in components, {len(ev['exclusions'])} excluded\n")
    out.append("| Component | Files | Beats | What it does |\n| --- | ---: | --- | --- |")
    for c in ev["components"]:
        out.append(f"| `{c['id']}` | {len(c['files'])} | {', '.join(c['beat_ids'])} | {c['explanation']} |")
    out.append("\n| Code beat | Source | Result beat | Observed |\n| --- | --- | --- | --- |")
    ex = {e["beat_id"]: e for e in ev["excerpts"]}
    for pr in ev["code_result_pairs"]:
        e = ex[pr["code_beat"]]
        out.append(f"| {pr['code_beat']} | `{e['path']}:{e['start_line']}–{e['end_line']}` | {pr['result_beat']} | {pr['observation']} |")
    reasons = {}
    for x in ev["exclusions"]:
        reasons.setdefault(x["reason"], []).append(x["path"])
    if reasons:
        out.append("\n**Excluded, with the reason recorded in the ledger:**\n")
        for r, paths in reasons.items():
            shown = ", ".join(f"`{q}`" for q in paths[:6]) + (f" and {len(paths) - 6} more" if len(paths) > 6 else "")
            out.append(f"- {len(paths)} file(s): {shown}. {r}")
    out.append("")
out.append("## Shown on still cards and figures rather than as Workbench excerpts\n\n"
           "- `game/tests/test_rudy_clips.gd` lines 419-421 (`track_problems()`'s property check) on the missing-property card (B10), with the "
           "probe's track row from `evidence/load-error-probe/`.\n"
           "- `game/animations/rudy_animations.tres`, the slash's key times, values and transitions (lines 416-419, 428-431, 440-443, 452-455), on the "
           "phase figure (B15), parsed from the file and asserted to be ticks 0, 2, 5 (4 for the arc), 11 and 17 over 60.\n"
           "- `CHANGE-BRIEF.md` section 2.2's phase table and Revisions 5-6's strip tables (B15, B17): each quoted row is asserted to be in the file.\n"
           "- Every frame's tick, Grip and hitbox state on the strip cards (B04, B07, B14, B17, B18) is parsed from that capture's own log; every phrase "
           "quoted from `TUNING.md` or `TEST-REPORT.md` is asserted to be there by `tools/make_stills.py`.\n")
(REEL / "COMPONENTS.md").write_text("\n".join(out) + "\n")

pr = [f"# PROMPTS — {title}\n", "Every prompt shown or read in the film.\n"]
for b in beats:
    r = b["shot"].get("remotion", {})
    if r.get("pattern") == "ClaudeComposerAsk":
        p = r["props"]
        pr.append(f"## {b['beat_id']} — {p['greeting']}\n\n**Status:** {'reconstructed prompt — illustrative, not a transcript' if b['beat_id'] == 'B00' else 'suggested prompt for the viewer'}\n\n```text\n{p['command']}\n```\n")
        if p.get("output"):
            pr.append("On-screen result lines (each checked in FACTCHECK.md):\n\n" + "\n".join(f"- {o}" for o in p["output"]) + "\n")
pr.append("## The prompts behind the work shown\n\n"
          "The film quotes no prompt from the build sessions. The scoped `claude -p` prompts it refers to are in the assignment folder's `sessions/`, "
          "`prompt-1.txt` to `prompt-18c.txt`, each beside its answer; `sessions/transcripts/` holds the redacted streams. The ones the film names: "
          "`prompt-3.txt` (the sheet), `prompt-4.txt` and `prompt-5.txt` (the sprite clips and the wiring), `prompt-6.txt` and `6b` (the rig's parts), "
          "`prompt-7.txt` and `prompt-8.txt` (the rig clip and its wiring), `prompt-9.txt`, `10`, `13` and `14` (the state and edge tests), `prompt-12.txt` "
          "(the library's move and `step`), `prompt-17.txt` and `17b` (the previews), `prompt-18.txt`, `18b` and `18c` (the r0 reading, the r1 change, the r1 comparison).\n")
(REEL / "PROMPTS.md").write_text("\n".join(pr))

rf = [f"# RIFF — {title}\n",
      "Liam, in for Bear (Kokoro `am_onyx`). Observations come from the captures and the logs; mechanisms from the source named in the "
      "preceding beat. Every verdict on how the motion reads is shuai-z's (TUNING.md, TEST-REPORT.md); Claude's strip readings and predictions "
      "are labelled as claims. The gameplay is a scripted route, not a playtest.\n",
      "| Beat | Artifact | Visible observation | Interpretation (source) | Narration | Next experiment |",
      "| --- | --- | --- | --- | --- | --- |"]
for i, b in enumerate(beats):
    s = b["shot"]
    if not (s.get("capture_plan") or s.get("still_plan")):
        continue
    prev = beats[i - 1]
    src = (f"`{prev['excerpt']['project']}/{prev['excerpt']['path']}:{prev['excerpt']['start_line']}–{prev['excerpt']['end_line']}`"
           if prev.get("excerpt") else "TUNING.md, TEST-REPORT.md, CHANGE-BRIEF.md")
    rf.append(f"| {b['beat_id']} | {visual(b)} | {s['observation']} | {src} | {b['narration_text']} | {NEXT.get(b['beat_id'], '')} |")
(REEL / "RIFF.md").write_text("\n".join(rf) + "\n")
print(f"docs written; film {t:.1f} s")
